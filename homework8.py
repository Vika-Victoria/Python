# Завдання 6
# Користувач вводить будь-яке ціле число. Необхідно з цього цілого числа видалити всі цифри 3 і 6 і вивести назад на екран.

try:
    number = int(input("Введіть ціле число: "))

    result = 0

    # щоб правильно поставити цифру на її місце в новому числі
    # 1 → одиниці
    # 10 → десятки
    # 100 → сотні
    # 1000 → тисячі
    place = 1

    while number != 0:
        # % 10 — отримуємо останню цифру
        if number % 10 != 3 and number % 10 != 6:
            result = result + (number % 10) * place
            place = place * 10

        # відкидаємо останню цифруe
        number //= 10

    print("Результат:", result)

except ValueError:
    print("Помилка: потрібно вводити число!")    