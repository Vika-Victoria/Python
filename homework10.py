# 1) Користувач вводить пароль.
# Умови:
# мінімум 8 символів;
# має бути хоча б одна цифра;
# має бути хоча б одна літера.

password = input("Введіть пароль: ")  # Користувач вводить пароль

has_digit = False  # Змінна показує, чи знайшли ми хоча б одну цифру
has_letter = False  # Змінна показує, чи знайшли ми хоча б одну літеру

for i in password:  # Перебираємо кожен символ пароля
    if i.isdigit():  # Перевіряємо, чи є поточний символ цифрою
        has_digit = True  # Якщо це цифра, запам'ятовуємо це

    if i.isalpha():  # Перевіряємо, чи є поточний символ літерою
        has_letter = True  # Якщо це літера, запам'ятовуємо це

if len(password) >= 8 and has_digit and has_letter:  # Перевіряємо всі три умови
    print("Пароль гарно сформовано")  # Якщо всі умови виконані
else:
    print("Пароль поганий!")  # Якщо хоча б одна умова не виконана   
 
# 2) Користувач вводить текст.
# Програма повинна визначити:
# загальну кількість символів;
# кількість літер;
# кількість цифр;
# кількість пробілів;
# кількість заданого символу;
# текст великими літерами;
# текст у зворотному порядку.
 

text = input("Введіть текст: ")

total = len(text)  # Рахуємо загальну кількість символів

letters = 0  # Лічильник літер
digits = 0  # Лічильник цифр
spaces = 0  # Лічильник пробілів

for i in text:  # Перебираємо кожен символ тексту

    if i.isalpha():  # Перевіряємо, чи є символ літерою
        letters += 1  # Збільшуємо кількість літер

    if i.isdigit():  # Перевіряємо, чи є символ цифрою
        digits += 1  # Збільшуємо кількість цифр

    if i == " ":  # Перевіряємо, чи є символ пробілом
        spaces += 1  # Збільшуємо кількість пробілів

symbol_count = text.count("а")  # Рахуємо кількість літери "а"

print("Загальна кількість символів:", total)
print("Кількість літер:", letters)
print("Кількість цифр:", digits)
print("Кількість пробілів:", spaces)
print("Кількість літери а:", symbol_count)
print("Текст великими літерами:", text.upper())
print("Текст у зворотному порядку:", text[::-1])